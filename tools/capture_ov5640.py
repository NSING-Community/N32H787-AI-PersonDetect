"""Request and show Y8 or hardware-JPEG frames from NSLink's CDC ACM port.

Refreshes a live window by default; pass --single to grab one frame and exit.
NSLink is selected by USB VID/PID: COMx in Windows, /dev/ttyACMx in Linux/WSL.
--port overrides detection; --list-ports shows the current runtime's devices.
USB/IP ownership must be switched outside this program before changing OS.
The view is shown at the received resolution unless --scale magnifies it.
The window is created once at that size and the program never resizes it again,
so it stays where you put it -- and drag it if you want it a different size.

The firmware keeps SDRAM disabled and can report person-detection metadata.
This client also supports builds without inference. --benchmark 100
measures received and decoded frames without opening a window. --jpeg on/off
selects hardware compression or raw Y8; JPEG is the default. Explicit auto
leaves the MCU mode alone. Unavailable inference never blocks image display.

Protocol, all little-endian:
  'OV56' | width:u16 | height:u16 | format:u32 | length:u32 | payload
format 1 is RGB565 and nothing else.  format 2 inserts a four-byte detection
record between the header and the payload -- person score:i8, no-person
score:i8, reserved, then flags (bit0 inference valid, bit1 the person class
won).  The record precedes the payload so the frame being received can be
annotated without waiting for the end of it.  Both scores are a two-class
softmax (scale 1/256, zero point -128), so either can be read as a probability.
Format 3 is a complete JPEG image generated by the N32H787 JPEG encoder; format
4 is JPEG plus the same four-byte detection record.  JPEG normally reduces the
wire time substantially. Formats 1/2 are retained for legacy RGB565 firmware.
Formats 5/6 are RGB565/JPEG with asynchronous inference: the four-byte detection
record is followed by preview frame ID, inference source frame ID, and source
age in milliseconds (three u32 values). The verdict is not for the live frame.
Formats 7/8 extend 5/6 with copy, preprocessing, and model Invoke microseconds
(three u32 values), measured on M7 for the same inference result.
Formats 9/10 carry raw Y8 (one byte per pixel), without metadata / with the
same timed metadata as format 8. Current firmware uses these for raw fallback
and emits a true single-component grayscale JPEG in formats 3/8.

Baud notes, measured on the N32H787_HMI_V1.1 board:
  * The MCU's USART1 is clocked at 300 MHz with no prescale, so it could reach
    18.75 Mbaud; the limit is the NSLink bridge, not the MCU.
  * The bridge takes its UART rate from this side's line coding, so --baud must
    match USER/src/n32h7xx_cfg.c or the link carries nothing at all.  Note that
    a mismatch is *silent*, not garbled, which makes it easy to blame the wrong
    end.
  * Earlier WSL tests: short exchanges survive rates that bulk transfer does not: a one-byte
    command round-trip still answers at 4 Mbaud, but sustained 38400-byte
    frames fail above ~1 Mbaud. The QVGA grayscale test at 921600 also lost
    payload chunks, so it is not a reliable bulk-transfer default.
The default is 921600: Windows native received 500/500 frames, whereas WSL
USB/IP lost payload bytes in 15/500 requests with the same firmware and baud.
A 10.3 KB frame takes ~112 ms on the 8N1 wire. JPEG size depends on the scene.
A 320x240 raw Y8 frame takes ~0.83 s;
raw previews are therefore substantially slower.

Legacy RGB565 byte order: 0x4300 = 0x6f emits the low byte first
and the default decode below assumes that.  Getting it backwards is subtle --
it scrambles R/G/B into each other rather than swapping two channels, so the
colour-bar test pattern still shows eight distinct saturated bars and the
capture looks plausible, while every real scene turns into rainbow contour
bands.  Verify byte order against the bar's *hues* (white, yellow, cyan, green,
magenta, red, blue, black), never against a count of distinct values.

Incomplete frames use a stall deadline to permit retrying. Missing bytes do
not by themselves identify whether the loss was in UART, the bridge or USB/IP.
Serial writes also have a deadline; flush/tcdrain is deliberately avoided.
"""
