void jpeg_encoder_config_tables(uint32_t frame_width, uint32_t frame_height,
                                uint32_t quality)
{
    JPEGENC_InitType JPEGENC_InitStruct;
    const uint32_t pixel_format = JPEGRBC_MONOCHROME;
    uint8_t quant0[64], quant1[64];
    if (quality < 1U) quality = 1U;
    if (quality > 100U) quality = 100U;
    const uint32_t scale = quality < 50U ? 5000U / quality : 200U - quality * 2U;
    /* Scale immutable Q50 tables on every init, never already-scaled values.
       JPEGENC_Init copies these into both hardware QT and emitted JPEG DQT. */
    for (uint32_t i = 0U; i < 64U; ++i) {
        uint32_t q0 = (Quantisation_table0[i] * scale + 50U) / 100U;
        uint32_t q1 = (Quantisation_table1[i] * scale + 50U) / 100U;
        quant0[i] = q0 < 1U ? 1U : q0 > 255U ? 255U : q0;
        quant1[i] = q1 < 1U ? 1U : q1 > 255U ? 255U : q1;
    }
    
    JPEGENC_InitStruct.HuffmanTable0.DCcode_offset = HT0_DCcodeoffset;
    JPEGENC_InitStruct.HuffmanTable0.ACcode_offset = HT0_ACcodeoffset;
    JPEGENC_InitStruct.HuffmanTable0.DCcode_start = HT0_DCcodestart;
    JPEGENC_InitStruct.HuffmanTable0.ACcode_start = HT0_ACcodestart;
    JPEGENC_InitStruct.HuffmanTable0.EOBS = 0x3000a;
    JPEGENC_InitStruct.HuffmanTable0.ZRLS = 0xa07f9;
    if(pixel_format != JPEGRBC_MONOCHROME)
    {
        JPEGENC_InitStruct.HuffmanTable1.DCcode_offset = HT1_DCcodeoffset;
        JPEGENC_InitStruct.HuffmanTable1.ACcode_offset = HT1_ACcodeoffset;
        JPEGENC_InitStruct.HuffmanTable1.DCcode_start = HT1_DCcodestart;
        JPEGENC_InitStruct.HuffmanTable1.ACcode_start = HT1_ACcodestart;
        JPEGENC_InitStruct.HuffmanTable1.EOBS = 0x10000;
        JPEGENC_InitStruct.HuffmanTable1.ZRLS = 0x903fa;
    }
    else
    {
        JPEGENC_InitStruct.HuffmanTable1.DCcode_offset = NULL;
        JPEGENC_InitStruct.HuffmanTable1.ACcode_offset = NULL;
        JPEGENC_InitStruct.HuffmanTable1.DCcode_start = NULL;
        JPEGENC_InitStruct.HuffmanTable1.ACcode_start = NULL;
        JPEGENC_InitStruct.HuffmanTable1.EOBS = 0x0000;
        JPEGENC_InitStruct.HuffmanTable1.ZRLS = 0x0000;
    }
    JPEGENC_InitStruct.HuffmanTable2.DCcode_offset = NULL;
    JPEGENC_InitStruct.HuffmanTable2.ACcode_offset = NULL;
    JPEGENC_InitStruct.HuffmanTable2.DCcode_start = NULL;
    JPEGENC_InitStruct.HuffmanTable2.ACcode_start = NULL;
    JPEGENC_InitStruct.HuffmanTable2.EOBS = 0x0000;
    JPEGENC_InitStruct.HuffmanTable2.ZRLS = 0x0000;
    JPEGENC_InitStruct.HuffmanTable3.DCcode_offset = NULL;
    JPEGENC_InitStruct.HuffmanTable3.ACcode_offset = NULL;
    JPEGENC_InitStruct.HuffmanTable3.DCcode_start = NULL;
    JPEGENC_InitStruct.HuffmanTable3.ACcode_start = NULL;
    JPEGENC_InitStruct.HuffmanTable3.EOBS = 0x0000;
    JPEGENC_InitStruct.HuffmanTable3.ZRLS = 0x0000;
    if(pixel_format != JPEGRBC_MONOCHROME)
    {
        header_part_YUV[7] = frame_height/256U;
        header_part_YUV[8] = frame_height%256U;
        header_part_YUV[9] = frame_width/256U;
        header_part_YUV[10] = frame_width%256U;
        JPEGENC_InitStruct.header_address = header_part_YUV;
        JPEGENC_InitStruct.header_size = sizeof(header_part_YUV);
        JPEGENC_InitStruct.hufftab0_header_address = Huffman_table0;
        JPEGENC_InitStruct.hufftab0_header_size = sizeof(Huffman_table0);
        JPEGENC_InitStruct.hufftab1_header_address = Huffman_table1;
        JPEGENC_InitStruct.hufftab1_header_size = sizeof(Huffman_table1);
    }
    else
    {
        header_part_Gray[7] = frame_height/256U;
        header_part_Gray[8] = frame_height%256U;
        header_part_Gray[9] = frame_width/256U;
        header_part_Gray[10] = frame_width%256U;
        JPEGENC_InitStruct.header_address = header_part_Gray;
        JPEGENC_InitStruct.header_size = sizeof(header_part_Gray);
        JPEGENC_InitStruct.hufftab0_header_address = Huffman_table0;
        JPEGENC_InitStruct.hufftab0_header_size = sizeof(Huffman_table0);
        JPEGENC_InitStruct.hufftab1_header_address = NULL;
        JPEGENC_InitStruct.hufftab1_header_size = 0U;
    }
    JPEGENC_InitStruct.hufftab2_header_address = NULL;
    JPEGENC_InitStruct.hufftab2_header_size = 0U;
    JPEGENC_InitStruct.hufftab3_header_address = NULL;
    JPEGENC_InitStruct.hufftab3_header_size = 0U;
    JPEGENC_InitStruct.footer_address = footer_part;
    JPEGENC_InitStruct.footer_size = sizeof(footer_part);
    if(pixel_format != JPEGRBC_MONOCHROME)
    {
        JPEGENC_InitStruct.output_select = JPEGENC_OUTPUT_QT0 | JPEGENC_OUTPUT_HT0 | JPEGENC_OUTPUT_QT1 | JPEGENC_OUTPUT_HT1;
        JPEGENC_InitStruct.QT0_address = quant0;
        JPEGENC_InitStruct.QT1_address = quant1;
    }
    else
    {
        JPEGENC_InitStruct.output_select = JPEGENC_OUTPUT_QT0 | JPEGENC_OUTPUT_HT0;
        JPEGENC_InitStruct.QT0_address = quant0;
        JPEGENC_InitStruct.QT1_address = NULL;
    }
    JPEGENC_InitStruct.QT2_address = NULL;
    JPEGENC_InitStruct.QT3_address = NULL;
    JPEGENC_InitStruct.restart_interval = JPEGENC_RESSART_DISABLE;
    JPEGENC_InitStruct.interval_num = 1U;
    JPEGENC_InitStruct.C0QT_select = 0U;
    JPEGENC_InitStruct.C1QT_select = 1U;
    JPEGENC_InitStruct.C2QT_select = 1U;
    JPEGENC_InitStruct.C3QT_select = 0U;
    JPEGENC_InitStruct.C0HT_select = 0U;
    JPEGENC_InitStruct.C1HT_select = 1U;
    JPEGENC_InitStruct.C2HT_select = 1U;
    JPEGENC_InitStruct.C3HT_select = 0U;
    JPEGENC_InitStruct.Corereset   = JPEGENC_CORERST_DISABLE;
    JPEGENC_Init(&JPEGENC_InitStruct);
}
